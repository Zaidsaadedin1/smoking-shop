function product(
  id: string,
  slug: string,
  name: string,
  categorySlug: string,
  brand: string,
  shortDescription: string,
  description: string,
  images: string[],
  variants: StoreProduct['variants'],
  tags: string[],
  meta: Partial<StoreProduct> = {}
): StoreProduct {
  return {
    id,
    slug,
    name,
    categorySlug,
    brand,
    shortDescription,
    description,
    images: images.map((url, index) => ({
      id: `${id}-img-${index + 1}`,
      url,
      alt: name,
      isPrimary: index === 0,
    })),
    variants,
    tags,
    status: 'active',
    rating: meta.rating ?? 4.8,
    reviewCount: meta.reviewCount ?? 18,
    isFeatured: meta.isFeatured ?? false,
    isNew: meta.isNew ?? false,
  };
}

